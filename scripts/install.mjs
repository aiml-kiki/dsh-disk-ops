#!/usr/bin/env node
/**
 * Build + package the plugin as a local bundle.
 *
 *   node scripts/install.mjs            # build, hash, regenerate cordis.patch.yml
 *   node scripts/install.mjs --dist     # same, but copy lib/ into dist/<hash>/
 *   node scripts/install.mjs --uninstall
 *
 * The actual bundle registration is done by DSH's plugin manager (or by hand:
 * add dsh-disk-ops to the profile's dsh.profile.bundles). This script only
 * produces a stable host entry URL so the ESM cache cannot serve stale code.
 */

import { createHash } from 'node:crypto';
import { spawn } from 'node:child_process';
import { cp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = new Set(process.argv.slice(2));

if (args.has('--uninstall')) {
  await rm(join(root, 'dist'), { recursive: true, force: true });
  await writeFile(join(root, 'cordis.patch.yml'), '# dsh-disk-ops: not installed\n', 'utf8');
  process.stdout.write('Removed dist/. Remove the bundle from the DSH profile and delete $DSH_HOME/disk-ops to finish.\n');
  process.exit(0);
}

await run('node', [join(root, 'scripts', 'build-client.mjs')]);

const files = (await listFiles(join(root, 'lib'))).sort();
const hash = createHash('sha256');
for (const file of files) {
  hash.update(relative(join(root, 'lib'), file));
  hash.update(await readFile(file));
}
const revision = hash.digest('hex').slice(0, 8);
const distDir = join(root, 'dist', revision);

if (args.has('--dist')) {
  await rm(join(root, 'dist'), { recursive: true, force: true });
  await mkdir(distDir, { recursive: true });
  await cp(join(root, 'lib'), distDir, { recursive: true });
}

const entry = args.has('--dist') ? join(distDir, 'index.js') : join(root, 'lib', 'index.js');
const patch = [
  '# dsh-disk-ops bundle patch (generated by scripts/install.mjs).',
  `# revision=${revision}`,
  '- insert:',
  '    - id: dsh-disk-ops',
  `      name: "file://${entry}"`,
  '      config: {}',
  '',
].join('\n');
await writeFile(join(root, 'cordis.patch.yml'), patch, 'utf8');

process.stdout.write(
  [
    `built client + host entry (rev ${revision})`,
    `patch: ${join(root, 'cordis.patch.yml')}`,
    `entry: ${entry}`,
    '',
    'Next: install as a local bundle, e.g. through the DSH plugin manager:',
    '  plugin_manager install_bundle target="' + root + '"',
    'or add "dsh-disk-ops" to the profile package.json dsh.profile.bundles and restart DSH.',
    '',
  ].join('\n'),
);

/**
 * @param {string} command
 * @param {string[]} argv
 */
function run(command, argv) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, argv, { stdio: 'inherit' });
    child.on('error', reject);
    child.on('close', (code) => (code === 0 ? resolve() : reject(new Error(`${command} exited ${code}`))));
  });
}

/**
 * @param {string} dir
 * @returns {Promise<string[]>}
 */
async function listFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await listFiles(path)));
    else files.push(path);
  }
  return files;
}
